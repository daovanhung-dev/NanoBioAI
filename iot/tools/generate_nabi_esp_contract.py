#!/usr/bin/env python3
"""Generate the Dart and ESP-IDF views of the Nabi/OSTB contract."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "iot/nabi_esp_contract.json"
DART = ROOT / "lib/app_versions/v1/features/nabi_esp_assistant/data/services/nabi_esp_contract.g.dart"
KOTLIN = ROOT / "android/app/src/main/kotlin/com/nanobioai/app/nabi_esp/NabiEspGeneratedContract.kt"
HEADER = ROOT / "iot/xiaozhi-esp32/main/nabi_esp_contract.h"


def render() -> tuple[str, str, str]:
    contract = json.loads(SOURCE.read_text(encoding="utf-8"))
    # ESP-IDF's BLE advertising/GATT APIs consume the 128-bit UUID as its
    # little-endian wire representation. Android parses that byte sequence
    # back to the canonical UUID string from the shared contract.
    uuid_bytes = bytes.fromhex(contract["bleServiceUuid"].replace("-", ""))[::-1]
    if len(uuid_bytes) != 16:
        raise ValueError("bleServiceUuid must contain 16 bytes")
    dart = """// Generated by iot/tools/generate_nabi_esp_contract.py. Do not edit.
abstract final class NabiEspContract {
  static const contractVersion = %(contractVersion)d;
  static const protocolVersion = %(protocolVersion)d;
  static const port = %(port)d;
  static const otaPath = '%(otaPath)s';
  static const websocketPath = '%(websocketPath)s';
  static const deviceKeyHeader = '%(deviceKeyHeader)s';
  static const bleNamePrefix = '%(bleNamePrefix)s';
  static const bleServiceUuid = '%(bleServiceUuid)s';
  static const bleSecurityUsername = '%(bleSecurityUsername)s';
  static const bleConfigEndpoint = '%(bleConfigEndpoint)s';

  static String otaUrl(String host, {int? portOverride}) => 'http://$host:${portOverride ?? port}$otaPath';
  static String websocketUrl(String host, {int? portOverride}) => 'ws://$host:${portOverride ?? port}$websocketPath';
}
""" % contract
    kotlin = """// Generated by iot/tools/generate_nabi_esp_contract.py. Do not edit.
package com.nanobioai.app.nabi_esp

internal object NabiEspGeneratedContract {
    const val contractVersion = %(contractVersion)d
    const val protocolVersion = %(protocolVersion)d
    const val port = %(port)d
    const val otaPath = "%(otaPath)s"
    const val websocketPath = "%(websocketPath)s"
    const val deviceKeyHeader = "%(deviceKeyHeader)s"
    const val bleNamePrefix = "%(bleNamePrefix)s"
    const val bleServiceUuid = "%(bleServiceUuid)s"
    const val bleSecurityUsername = "%(bleSecurityUsername)s"
    const val bleConfigEndpoint = "%(bleConfigEndpoint)s"
}
""" % contract
    header = """// Generated by iot/tools/generate_nabi_esp_contract.py. Do not edit.
#pragma once

#define NABI_CONTRACT_VERSION %(contractVersion)d
#define NABI_PROTOCOL_VERSION %(protocolVersion)d
#define NABI_AI_PORT %(port)d
#define NABI_OTA_PATH "%(otaPath)s"
#define NABI_WEBSOCKET_PATH "%(websocketPath)s"
#define NABI_DEVICE_KEY_HEADER "%(deviceKeyHeader)s"
#define NABI_BLE_NAME_PREFIX "%(bleNamePrefix)s"
#define NABI_BLE_SERVICE_UUID "%(bleServiceUuid)s"
#define NABI_BLE_SERVICE_UUID_BYTES { %(uuidBytes)s }
#define NABI_BLE_SECURITY_USERNAME "%(bleSecurityUsername)s"
#define NABI_BLE_CONFIG_ENDPOINT "%(bleConfigEndpoint)s"
""" % {**contract, "uuidBytes": ", ".join(f"0x{value:02x}" for value in uuid_bytes)}
    return dart, kotlin, header


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dart, kotlin, header = render()
    targets = ((DART, dart), (KOTLIN, kotlin), (HEADER, header))
    stale = []
    for path, content in targets:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Generated contract is stale: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print("Nabi/ESP contract outputs are in sync." if args.check else "Generated Nabi/ESP contract outputs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
