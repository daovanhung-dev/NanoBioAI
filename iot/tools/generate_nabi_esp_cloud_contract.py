#!/usr/bin/env python3
"""Generate the cloud Nabi contract constants used by Flutter, Android and ESP."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "iot/nabi_esp_cloud_contract.json"
DART = ROOT / "lib/app_versions/v1/features/nabi_esp_assistant/data/services/nabi_esp_cloud_contract.g.dart"
KOTLIN = ROOT / "android/app/src/main/kotlin/com/nanobioai/app/nabi_esp/NabiEspCloudContract.kt"
HEADER = ROOT / "iot/nabi-esp32/main/nabi_esp_cloud_contract.h"


def render() -> tuple[str, str, str]:
    contract = json.loads(SOURCE.read_text(encoding="utf-8"))
    uuid_bytes = bytes.fromhex(contract["bleServiceUuid"].replace("-", ""))[::-1]
    if len(uuid_bytes) != 16:
        raise ValueError("bleServiceUuid must contain 16 bytes")
    dart = """// Generated by iot/tools/generate_nabi_esp_cloud_contract.py. Do not edit.
abstract final class NabiEspCloudContract {
  static const contractVersion = %(contractVersion)d;
  static const protocolVersion = %(protocolVersion)d;
  static const apiBaseUrl = '%(apiBaseUrl)s';
  static const websocketUrl = '%(websocketUrl)s';
  static const apBaseUrl = '%(apBaseUrl)s';
  static const apStatusPath = '%(apStatusPath)s';
  static const apProvisionPath = '%(apProvisionPath)s';
  static const pairingSessionPath = '%(pairingSessionPath)s';
  static const claimPath = '%(claimPath)s';
  static const deviceLoginPath = '%(deviceLoginPath)s';
  static const refreshPath = '%(refreshPath)s';
}
""" % contract
    kotlin = """// Generated by iot/tools/generate_nabi_esp_cloud_contract.py. Do not edit.
package com.nanobioai.app.nabi_esp

internal object NabiEspCloudContract {
    const val contractVersion = %(contractVersion)d
    const val protocolVersion = %(protocolVersion)d
    const val apiBaseUrl = "%(apiBaseUrl)s"
    const val websocketUrl = "%(websocketUrl)s"
    const val apBaseUrl = "%(apBaseUrl)s"
    const val apStatusPath = "%(apStatusPath)s"
    const val apProvisionPath = "%(apProvisionPath)s"
    const val apSsidPrefix = "%(apSsidPrefix)s"
    const val deviceLoginPath = "%(deviceLoginPath)s"
    const val bleNamePrefix = "%(bleNamePrefix)s"
    const val bleServiceUuid = "%(bleServiceUuid)s"
    const val bleSecurityUsername = "%(bleSecurityUsername)s"
    const val bleConfigEndpoint = "%(bleConfigEndpoint)s"
}
""" % contract
    header = """// Generated by iot/tools/generate_nabi_esp_cloud_contract.py. Do not edit.
#pragma once

#define NABI_CLOUD_CONTRACT_VERSION %(contractVersion)d
#define NABI_CLOUD_PROTOCOL_VERSION %(protocolVersion)d
#define NABI_CLOUD_API_BASE_URL "%(apiBaseUrl)s"
#define NABI_CLOUD_WS_URL "%(websocketUrl)s"
#define NABI_CLOUD_AP_BASE_URL "%(apBaseUrl)s"
#define NABI_CLOUD_AP_STATUS_PATH "%(apStatusPath)s"
#define NABI_CLOUD_AP_PROVISION_PATH "%(apProvisionPath)s"
#define NABI_CLOUD_AP_SSID_PREFIX "%(apSsidPrefix)s"
#define NABI_CLOUD_PAIRING_SESSION_PATH "%(pairingSessionPath)s"
#define NABI_CLOUD_CLAIM_PATH "%(claimPath)s"
#define NABI_CLOUD_DEVICE_LOGIN_PATH "%(deviceLoginPath)s"
#define NABI_CLOUD_REFRESH_PATH "%(refreshPath)s"
#define NABI_CLOUD_BLE_NAME_PREFIX "%(bleNamePrefix)s"
#define NABI_CLOUD_BLE_SERVICE_UUID_BYTES { %(uuidBytes)s }
#define NABI_CLOUD_BLE_SECURITY_USERNAME "%(bleSecurityUsername)s"
#define NABI_CLOUD_BLE_CONFIG_ENDPOINT "%(bleConfigEndpoint)s"
""" % {**contract, "uuidBytes": ", ".join(f"0x{value:02x}" for value in uuid_bytes)}
    return dart, kotlin, header


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dart, kotlin, header = render()
    outputs = ((DART, dart), (KOTLIN, kotlin), (HEADER, header))
    stale = [
        str(path.relative_to(ROOT))
        for path, content in outputs
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if args.check:
        if stale:
            print("Stale Nabi cloud contract outputs: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
